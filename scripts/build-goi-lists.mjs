function toPt(en) {
  if (!en) return ''
  const s = String(en).trim()
  if (!s) return ''
  if (/[áàâãéêíóôõúçÁÀÂÃÉÊÍÓÔÕÚÇ]/.test(s) && !/^(to |the |a |an )/i.test(s)) return s
  const low = s.toLowerCase()
  if (MAP[low]) return MAP[low]
  const first = low.split(/[;,]/)[0].trim()
  if (MAP[first]) return MAP[first]
  for (const [k, v] of Object.entries(MAP)) {
    if (first === k || low.startsWith(k + ';') || low.startsWith(k + ',')) return v
  }
  return s.replace(/^to /i, '').replace(/\b(the|a|an)\b/gi, '').trim()
}

const VERB_FALLBACK = {
  aru: 'haver / ter (coisas)',
  iru: 'existir (seres vivos)',
  kakaru: 'levar (tempo/dinheiro)',
  magaru: 'virar',
  noru: 'embarcar / montar',
  wasureru: 'esquecer',
}

const nounRows = []
for (const chunk of N5_NOUN_CHUNKS) {
  for (const r of chunk.rows) {
    const pdf =
      nounsPdf.find((x) => x.jp === r.jp && (!r.r || x.r === r.r)) ||
      nounsPdf.find((x) => x.jp === r.jp)
    const pt = toPt(r.pt) || toPt(pdf?.pt) || toPt(pdf?.en) || r.pt || ''
    nounRows.push({
      jp: r.jp,
      kj: pdf?.kj || '',
      r: r.r || pdf?.r || '',
      pt: pt || r.pt || '',
    })
  }
}

const verbs = N5_VERBS.map((v) => ({
  ...v,
  pt: v.pt || VERB_FALLBACK[v.r] || toPt(v.pt) || '',
}))
const iAdj = N5_I_ADJ.map((a) => ({ ...a, pt: toPt(a.pt) || a.pt }))
const naAdj = N5_NA_ADJ.map((a) => ({ ...a, pt: toPt(a.pt) || a.pt }))

const groups = {}
for (const n of nounRows) {
  const letter = (n.r || n.jp)[0]?.toLowerCase() || '#'
  const g = /[a-z]/.test(letter) ? letter : '#'
  if (!groups[g]) groups[g] = []
  groups[g].push(n)
}
const nounGroups = Object.keys(groups)
  .sort()
  .map((letter) => ({ id: letter, t: letter.toUpperCase(), rows: groups[letter] }))

const stillEn = nounRows.filter(
  (r) => /^[a-zA-Z ,;.'()-]+$/.test(r.pt || '') && !/[áàâãéêíóôõúç]/.test(r.pt || ''),
)
console.log('nouns', nounRows.length, 'still EN-ish', stillEn.length)
console.log('verbs', verbs.length, 'empty', verbs.filter((v) => !v.pt).length)
console.log('i', iAdj.length, 'na', naAdj.length)

function dump(name, value) {
  return `/** Listas 語彙 N5 (escopo PDF). Glosses PT do app. */\nexport const ${name} = ${JSON.stringify(value, null, 2)}\n`
}

